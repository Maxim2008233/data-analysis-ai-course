def clean(name):
    """Название как текст: дефисы и подчёркивания → пробелы."""
    return name.replace("_", " ").replace("-", " ")


def english(name, language):
    if language == "Latina":
        return LATIN[name]
    if language == "Español":
        return SPANISH[name]
    return ENGLISH_FIX.get(name, clean(name).lower())
